/* Renders the six category cards on the home page.

   The home page used to list all 26 printables. That made it long, gave every
   printable the same weight, and meant the only way to browse was to scroll.
   Each category now has its own page at /<slug>/ — generated by
   tools/build-categories.mjs — and the home page points at those.

   The drawings live in assets/js/art.js, because the category pages draw the
   same cards at build time. */
(function () {
  var el = AP.el;
  var ART = AP.ART;

  /* The whole card is clickable via the stretched-link pattern, so the card is
     one target without nesting anchors — which is invalid HTML and breaks
     keyboard navigation. */
  function categoryCard(cat) {
    var items = AP.byCategory(cat.id);
    var live = items.filter(function (p) { return p.status === 'live'; });
    var names = live.slice(0, 5).map(function (p) { return p.name; });
    var rest = live.length - names.length;

    return el('div', { class: 'card' }, [
      el('div', { class: 'card-art', html: AP.svg('0 0 72 60', ART[cat.art] || ART.calendar) }),
      el('div', { class: 'card-body' }, [
        el('div', { class: 'card-title' }, [
          el('a', { class: 'card-link', href: cat.slug + '/' },
             [el('h3', { text: cat.label })])
        ]),
        el('p', { text: cat.blurb }),
        el('ul', {}, names.map(function (n) { return el('li', { text: n }); })
          .concat(rest > 0 ? [el('li', { class: 'more', text: 'and ' + rest + ' more' })] : [])),
        el('a', { class: 'card-go', href: cat.slug + '/',
                  text: 'See all ' + live.length + ' →' })
      ])
    ]);
  }

  function init() {
    var root = AP.$('#catalogue');
    if (!root) return;
    var total = AP.PRINTABLES.filter(function (p) { return p.status === 'live'; }).length;

    root.appendChild(el('section', { class: 'section' }, [
      el('div', { class: 'section-head' }, [
        el('h2', { text: 'Browse by category' }),
        el('p', { text: total + ' printables, free, every one at true scale on the ' +
                        'paper size you pick.' })
      ]),
      el('div', { class: 'cards' }, AP.CATEGORIES.map(categoryCard))
    ]));
  }

  if (document.readyState === 'loading') document.addEventListener('DOMContentLoaded', init);
  else init();
})();
