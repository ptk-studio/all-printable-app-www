AP.byCategory = function (catId) {
  return AP.PRINTABLES.filter(function (p) { return p.cat === catId; });
};

AP.category = function (catId) {
  return AP.CATEGORIES.filter(function (c) { return c.id === catId; })[0] || null;
};
